import { renderSafeMarkdown } from '../lib/markdown.js';
import type { AnalysisJob } from '../../../shared/types.js';

// Markdown report of one job, built only from data already stored on the job.
// Sample-derived text is wrapped in code spans/blocks so it can't inject Markdown or HTML.

const code = (v: unknown) => `\`${String(v ?? '').replace(/`/g, 'ˋ').replace(/\n/g, ' ')}\``;
const fence = (text: string) => `\`\`\`\n${text.replace(/```/g, 'ˋˋˋ')}\n\`\`\``;
const cap = <T>(arr: T[] | undefined, n: number) => (arr ?? []).slice(0, n);

export function buildMarkdownReport(job: AnalysisJob): string {
  const out: string[] = [];
  const name = 'fileName' in job.input ? job.input.fileName : 'url' in job.input ? job.input.url : job.input.type === 'evm' ? job.input.value : job.id;
  const r = job.result;

  out.push(`# Web RE Engine report: ${code(name)}`, '');
  out.push(`- **Job:** ${code(job.id)}`, `- **Type:** ${job.type}`, `- **Status:** ${job.status}`, `- **Created:** ${job.createdAt}`);
  if (job.tags?.length) out.push(`- **Tags:** ${job.tags.map(code).join(' ')}`);
  out.push('');

  if (job.notes?.trim()) out.push('## Analyst notes', '', job.notes.trim(), '');

  const ai = job.explanations?.job;
  if (ai) out.push('## AI explanation', '', `_Generated by ${ai.model} on ${ai.createdAt}${ai.note ? ` — ${ai.note}` : ''}_`, '', ai.text, '');

  if (job.fingerprint) {
    const f = job.fingerprint;
    out.push('## Fingerprint', '', '| | |', '|---|---|');
    out.push(`| MD5 | ${code(f.md5)} |`, `| SHA-1 | ${code(f.sha1)} |`, `| SHA-256 | ${code(f.sha256)} |`, `| Size | ${f.size.toLocaleString()} bytes |`, `| Entropy | ${f.entropy.toFixed(3)} / 8 |`, '');
  }

  if (r?.type === 'native') {
    out.push('## Binary', '', `- **Format:** ${r.format} (${r.architecture})`, `- **Entry point:** ${code(r.entryPoint ?? 'unknown')}`, `- **Analyzer:** ${r.provider}, pseudo-code: ${r.decompiler ?? 'none'}`, `- **Functions analyzed:** ${r.functions.length}; imports: ${r.imports.length}; exports: ${r.exports.length}`);
    if (r.packer) {
      out.push(`- **Packer/container:** ${r.packer.kind} ${r.packer.version ?? ''} — ${r.packer.details}`);
      if (r.packer.entryPoints?.length) out.push(`- **Entry-point scripts:** ${r.packer.entryPoints.map(code).join(', ')}`);
      if (r.packer.pythonModules) out.push(`- **Third-party Python modules:** ${r.packer.pythonModules.thirdParty.map(code).join(', ') || 'none'}`);
    }
    out.push('');
    if (r.sections.length) {
      out.push('### Sections', '', '| Name | Address | Size | Perms | Entropy |', '|---|---|---|---|---|');
      for (const s of r.sections) out.push(`| ${code(s.name)} | ${code(s.address)} | ${s.size} | ${s.permissions} | ${s.entropy?.toFixed(2) ?? ''} |`);
      out.push('');
    }
    if (r.imports.length) {
      const byLib = new Map<string, string[]>();
      for (const i of r.imports) byLib.set(i.library || '(unknown)', [...(byLib.get(i.library || '(unknown)') ?? []), i.name]);
      out.push('### Imports', '');
      for (const [lib, names] of byLib) out.push(`- ${code(lib)}: ${cap(names, 60).map(code).join(', ')}${names.length > 60 ? ` … (+${names.length - 60})` : ''}`);
      out.push('');
    }
  } else if (r?.type === 'android') {
    out.push('## Android package', '', `- **Package:** ${code(r.packageName)} ${code(r.version)}`, `- **SDK:** min ${r.minSdk ?? '?'}, target ${r.targetSdk ?? '?'}`);
    out.push(`- **Permissions (${r.permissions.length}):** ${r.permissions.map(code).join(', ')}`);
    const exported = [...r.activities, ...r.services, ...r.receivers, ...r.providers].filter((c) => c.exported);
    out.push(`- **Exported components (${exported.length}):** ${exported.map((c) => code(c.name)).join(', ') || 'none'}`, '');
  } else if (r?.type === 'browser') {
    out.push('## Web page', '', `- **URL:** ${code(r.url)}`, `- **Requests:** ${r.networkRequests.length}; scripts: ${r.scriptSources.length}; cookies: ${r.cookies.length}`, '');
  } else if (r?.type === 'dotnet') {
    out.push('## .NET assembly', '', `- **Framework:** ${r.targetFramework}`, `- **Namespaces:** ${r.namespaces.length}; types: ${r.namespaces.reduce((n, ns) => n + ns.types.length, 0)}`, '');
  } else if (r?.type === 'javascript') {
    out.push('## JavaScript application', '', r.summary ? fence(r.summary) : '', `- **Modules:** ${r.modules.length}; entry points: ${r.entryPoints.map(code).join(', ')}`, '');
  } else if (r?.type === 'extension') {
    out.push(
      '## Browser extension',
      '',
      `- **Name:** ${code(r.name)} ${code(r.version)} (${r.browser}, Manifest V${r.manifestVersion}, ${r.packageFormat})`,
      `- **Risk:** ${r.riskLevel.toUpperCase()} (${r.riskScore}/100)`,
      `- **Background:** ${r.background.kind}${r.background.files.length ? ` ${r.background.files.map(code).join(', ')}` : ''}`,
      `- **Updates from:** ${r.updateUrl ? code(r.updateUrl) : 'store default'}${r.offStoreUpdates ? ' — **outside the official store**' : ''}`,
      ''
    );
    if (r.riskReasons.length) {
      out.push('### Why this risk level', '');
      for (const reason of r.riskReasons) out.push(`- ${reason}`);
      out.push('');
    }
    const perms = [...r.permissions, ...r.hostPermissions].filter((p) => p.risk !== 'low');
    if (perms.length) {
      out.push('### Sensitive permissions', '', '| Permission | Risk | Why it matters |', '|---|---|---|');
      for (const p of perms) out.push(`| ${code(p.name)}${p.optional ? ' (optional)' : ''} | ${p.risk} | ${p.reason} |`);
      out.push('');
    }
    if (r.findings.length) {
      out.push('### Code findings', '');
      for (const f of r.findings) {
        out.push(`- **[${f.severity}] ${f.title}** — ${f.description}`);
        for (const loc of f.locations.slice(0, 5)) out.push(`  - ${code(`${loc.file}:${loc.line}`)} ${code(loc.snippet.slice(0, 120))}`);
      }
      out.push('');
    }
    if (r.contentScripts.length) {
      out.push('### Content scripts', '');
      for (const cs of r.contentScripts) out.push(`- ${cs.js.map(code).join(', ') || '(CSS only)'} on ${cs.matches.map(code).join(', ')}`);
      out.push('');
    }
  } else if (r?.type === 'evm') {
    out.push('## EVM contract', '', `- **Bytecode length:** ${r.bytecodeLength}`, `- **Function selectors:** ${r.functionSelectors.map((s) => code(s.selector)).join(', ')}`, '');
  }

  if (job.yara?.matches.length) {
    out.push('## YARA matches', '', '| Severity | Rule | File | Description |', '|---|---|---|---|');
    for (const m of cap(job.yara.matches, 150)) out.push(`| ${m.meta.severity ?? 'low'} | ${code(m.rule)} | ${code(m.file)} | ${m.meta.description ?? ''} |`);
    out.push('');
  }

  if (job.capabilities?.capabilities.length) {
    out.push('## Capabilities (capa)', '');
    for (const c of job.capabilities.capabilities) out.push(`- ${c.name}${c.attack.length ? ` — ATT&CK ${c.attack.join(', ')}` : ''}`);
    out.push('');
  }

  const iocEntries = Object.entries(job.iocs ?? {}).filter(([, v]) => v.length > 0);
  if (iocEntries.length) {
    out.push('## Indicators of compromise', '');
    for (const [cat, values] of iocEntries) {
      const shown = cat === 'secrets' ? values.map((v) => (v.length <= 8 ? '********' : `${v.slice(0, 4)}…${v.slice(-4)}`)) : values;
      out.push(`### ${cat} (${values.length})`, '', fence(cap(shown, 200).join('\n')), '');
    }
  }

  if (r?.limitations?.length) {
    out.push('## Limitations', '');
    for (const l of r.limitations) out.push(`- ${l}`);
    out.push('');
  }

  const fnNotes = Object.entries(job.explanations ?? {}).filter(([k]) => k !== 'job');
  if (fnNotes.length) {
    out.push('## Other AI explanations', '');
    for (const [key, e] of fnNotes) out.push(`### ${code(key)}`, '', `_${e.model}, ${e.createdAt}_`, '', e.text, '');
  }

  return out.join('\n');
}

const REPORT_CSS = `
  body { font: 13px/1.5 -apple-system, "Segoe UI", Roboto, sans-serif; color: #1f2328; margin: 0; }
  h1 { font-size: 22px; border-bottom: 2px solid #238636; padding-bottom: 6px; }
  h2 { font-size: 17px; margin-top: 26px; border-bottom: 1px solid #d0d7de; padding-bottom: 4px; }
  h3 { font-size: 14px; }
  code { font: 11.5px ui-monospace, Menlo, monospace; background: #f6f8fa; padding: 1px 4px; border-radius: 4px; word-break: break-all; }
  pre { background: #f6f8fa; padding: 10px; border-radius: 6px; white-space: pre-wrap; word-break: break-all; }
  pre code { background: none; padding: 0; }
  table { border-collapse: collapse; width: 100%; margin: 8px 0; }
  th, td { border: 1px solid #d0d7de; padding: 4px 8px; text-align: left; vertical-align: top; }
  th { background: #f6f8fa; }
  a { color: #0969da; }
`;

export function buildHtmlReport(job: AnalysisJob): string {
  return `<!doctype html><html><head><meta charset="utf-8"><title>Web RE Engine report</title><style>${REPORT_CSS}</style></head><body>${renderSafeMarkdown(buildMarkdownReport(job))}</body></html>`;
}

// Chromium renders the report with scripts off and every network request blocked
export async function buildPdfReport(job: AnalysisJob): Promise<Buffer> {
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ headless: true });
  try {
    const context = await browser.newContext({ javaScriptEnabled: false });
    await context.route('**/*', (route) => route.abort());
    const page = await context.newPage();
    await page.setContent(buildHtmlReport(job), { waitUntil: 'load' });
    return await page.pdf({
      format: 'A4',
      margin: { top: '16mm', bottom: '16mm', left: '14mm', right: '14mm' },
      printBackground: true,
      displayHeaderFooter: true,
      headerTemplate: '<span></span>',
      footerTemplate: '<div style="font-size:8px;width:100%;text-align:center;color:#666">Web RE Engine · page <span class="pageNumber"></span>/<span class="totalPages"></span></div>',
    });
  } finally {
    await browser.close();
  }
}
